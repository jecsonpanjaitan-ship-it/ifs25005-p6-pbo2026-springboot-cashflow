package org.delcom.ifs25005springbootcashflow.adapter.repository;

import javax.sql.DataSource;
import org.springframework.jdbc.core.JdbcTemplate;

/** Membuat tabel bila belum ada (idempoten). */
public final class SchemaInitializer {

    static final String CREATE_USERS = """
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username VARCHAR(50) NOT NULL UNIQUE,
                password_hash VARCHAR(100) NOT NULL,
                full_name VARCHAR(100) NOT NULL,
                role VARCHAR(20) NOT NULL,
                photo_path VARCHAR(500)
            )""";

    static final String CREATE_TRANSACTIONS = """
            CREATE TABLE IF NOT EXISTS transactions (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER NOT NULL,
                description TEXT NOT NULL,
                amount BIGINT NOT NULL,
                type VARCHAR(20) NOT NULL,
                proof_path VARCHAR(500),
                created_at TIMESTAMP NOT NULL,
                CONSTRAINT fk_transactions_user FOREIGN KEY (user_id) REFERENCES users (id)
            )""";

    private SchemaInitializer() {
    }

    public static void initialize(DataSource dataSource) {
        JdbcTemplate jdbc = new JdbcTemplate(dataSource);
        jdbc.execute(CREATE_USERS);
        jdbc.execute(CREATE_TRANSACTIONS);
    }
}
